function regularFilesRecursively(directory) {
  const files = [];
  if (!fs.existsSync(directory)) return files;
  const visit = (current) => {
    const stat = fs.lstatSync(current);
    if (stat.isSymbolicLink()) {
      throw new Error(`refusing to copy symlink into Codex payload: ${current}`);
    }
    if (stat.isFile()) {
      files.push(current);
      return;
    }
    if (!stat.isDirectory()) return;
    for (const entry of fs.readdirSync(current).sort()) {
      visit(path.join(current, entry));
    }
  };
  visit(directory);
  return files;
}

function addCodexRuntimeArtifacts(artifacts, repoRoot) {
  const sourceRoot = path.join(repoRoot, PLUGIN_ROOT_RELATIVE);
  for (const entry of CODEX_RUNTIME_COPY_ENTRIES) {
    const source = path.join(sourceRoot, entry);
    for (const file of regularFilesRecursively(source)) {
      const relative = path.relative(sourceRoot, file);
      // Both payloads now launch hooks and the MCP server with `node` from the
      // host lookup, so the Codex copy is byte-identical to the Claude source.
      const content = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
      artifacts.set(
        path.join(CODEX_PLUGIN_ROOT_RELATIVE, relative),
        content,
      );
    }
  }
}

function addSkillDependencyArtifacts(artifacts, repoRoot, skill) {
  const sourceRoot = path.join(repoRoot, skill.sources.en);
  for (const file of regularFilesRecursively(sourceRoot)) {
    const relative = path.relative(sourceRoot, file);
    if (relative === 'SKILL.md' || relative.startsWith(`agents${path.sep}`)) continue;

    const content = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
    for (const payloadRoot of [PLUGIN_ROOT_RELATIVE, CODEX_PLUGIN_ROOT_RELATIVE]) {
      artifacts.set(
        path.join(payloadRoot, 'skills', skill.id, relative),
        content,
      );
    }
  }
}

function buildArtifactMap(contract, manifest, repoRoot = REPO_ROOT) {
  const artifacts = new Map();
  artifacts.set(CODEX_MANIFEST_RELATIVE, renderPluginManifest(contract, manifest));
  artifacts.set(MARKETPLACE_RELATIVE, renderMarketplace(contract));
  addCodexRuntimeArtifacts(artifacts, repoRoot);
  for (const skill of contract.skills) {
    addSkillDependencyArtifacts(artifacts, repoRoot, skill);
    const sourceRelative = path.join(
      PLUGIN_ROOT_RELATIVE,
      'skills',
      skill.id,
      'SKILL.md',
    );
    const sourceMarkdown = fs.readFileSync(
      path.join(repoRoot, sourceRelative),
      'utf8',
    );
    artifacts.set(
      path.join(CODEX_PLUGIN_ROOT_RELATIVE, 'skills', skill.id, 'SKILL.md'),
      renderCodexSkill(sourceMarkdown),
    );
    artifacts.set(
      path.join(CODEX_PLUGIN_ROOT_RELATIVE, 'skills', skill.id, 'agents', 'openai.yaml'),
      renderOpenAiYaml(skill),
    );
    artifacts.set(
      path.join(skill.sources.th, 'agents', 'openai.yaml'),
      renderOpenAiYaml(skill, 'th'),
    );
  }
  return artifacts;
}

function writeFileAtomic(filePath, content) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  const temporaryPath = `${filePath}.tmp-${process.pid}`;
  fs.writeFileSync(temporaryPath, content, 'utf8');
  fs.renameSync(temporaryPath, filePath);
}

function isCodexGeneratedPath(relativePath) {
  const normalized = path.normalize(relativePath);
  const root = path.normalize(CODEX_PLUGIN_ROOT_RELATIVE);
  return normalized === root || normalized.startsWith(`${root}${path.sep}`);
}

function compareArtifactMap(repoRoot, artifacts) {
  const errors = [];
  for (const [relativePath, expected] of artifacts) {
    const absolutePath = path.join(repoRoot, relativePath);
    if (!fs.existsSync(absolutePath)) {
      errors.push(`${relativePath} is missing; run node scripts/generate-platform-artifacts.cjs`);
      continue;
    }
    const actual = fs.readFileSync(absolutePath, 'utf8').replace(/\r\n/g, '\n');
    if (actual !== expected) {
      errors.push(`${relativePath} is stale; run node scripts/generate-platform-artifacts.cjs`);
    }
  }
  const expected = new Set(
    [...artifacts.keys()]
      .filter(isCodexGeneratedPath)
      .map((relativePath) => path.normalize(relativePath)),
  );
  const generatedRoot = path.join(repoRoot, CODEX_PLUGIN_ROOT_RELATIVE);
  for (const file of regularFilesRecursively(generatedRoot)) {
    const relativePath = path.normalize(path.relative(repoRoot, file));
    if (!expected.has(relativePath)) {
      errors.push(
        `${relativePath} is an orphaned generated artifact; run node scripts/generate-platform-artifacts.cjs`,
      );
    }
  }
  return errors;
}

function removeEmptyDirectories(directory, preserve) {
  if (!fs.existsSync(directory)) return;
  for (const entry of fs.readdirSync(directory)) {
    const child = path.join(directory, entry);
    if (fs.lstatSync(child).isDirectory()) removeEmptyDirectories(child, preserve);
  }
  if (directory !== preserve && fs.readdirSync(directory).length === 0) {
    fs.rmdirSync(directory);
  }
}

function removeGeneratedOrphans(repoRoot, artifacts) {
  const generatedRoot = path.join(repoRoot, CODEX_PLUGIN_ROOT_RELATIVE);
  if (!fs.existsSync(generatedRoot)) return;
  const expected = new Set(
    [...artifacts.keys()]
      .filter(isCodexGeneratedPath)
      .map((relativePath) => path.resolve(repoRoot, relativePath)),
  );
  for (const file of regularFilesRecursively(generatedRoot)) {
    if (!expected.has(path.resolve(file))) fs.unlinkSync(file);
  }
  removeEmptyDirectories(generatedRoot, generatedRoot);
}

function writeArtifactMap(repoRoot, artifacts) {
  removeGeneratedOrphans(repoRoot, artifacts);
  for (const [relativePath, content] of artifacts) {
    writeFileAtomic(path.join(repoRoot, relativePath), content);
  }
}

function generatePlatformArtifacts({ repoRoot = REPO_ROOT, check = false } = {}) {
  const { contract, manifest } = loadInputs(repoRoot);
  const contractErrors = validateContract(contract, manifest);
  if (contractErrors.length > 0) {
    return {
      ok: false,
      errors: contractErrors,
      written: [],
    };
  }

  const sourceErrors = [
    ...validateSharedSkills(repoRoot, contract),
    ...validatePackagingIsolation(repoRoot, contract),
  ];
  if (sourceErrors.length > 0) {
    return {
      ok: false,
      errors: sourceErrors,
      written: [],
    };
  }

  const artifacts = buildArtifactMap(contract, manifest, repoRoot);
  const errors = [];
  const written = [];

  if (check) {
    errors.push(...compareArtifactMap(repoRoot, artifacts));
  } else {
    writeArtifactMap(repoRoot, artifacts);
    written.push(...artifacts.keys());
  }

  return {
    ok: errors.length === 0,
    errors,
    written,
  };
}

function formatErrors(errors) {
  return errors.map((error) => `- ${error}`).join('\n');
}

function main(argv = process.argv.slice(2)) {
  const supported = new Set(['--check']);
  const unknown = argv.filter((argument) => !supported.has(argument));
  if (unknown.length > 0) {
    process.stderr.write(`Unknown argument(s): ${unknown.join(', ')}\n`);
    return 2;
  }

  const check = argv.includes('--check');
  let result;
  try {
    result = generatePlatformArtifacts({ check });
  } catch (error) {
    process.stderr.write(`Platform artifact generation failed: ${error.message}\n`);
    return 1;
  }

  if (!result.ok) {
    process.stderr.write(`${formatErrors(result.errors)}\n`);
    return 1;
  }

  if (check) {
    process.stdout.write('Platform artifacts are current and host-specific skills are portable.\n');
  } else {
    process.stdout.write(`Generated ${result.written.length} platform artifact(s).\n`);
  }
  return 0;
}

if (require.main === module) {
  process.exitCode = main();
}

