'use strict';

const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.resolve(__dirname, '..');
const CONTRACT_RELATIVE = 'contracts/workflows.json';
const MANIFEST_RELATIVE = 'manifest.json';
const PLUGIN_ROOT_RELATIVE = 'plugins/spk';
const CODEX_PLUGIN_ROOT_RELATIVE = 'plugins/spk-codex';
const CODEX_MANIFEST_RELATIVE = 'plugins/spk-codex/.codex-plugin/plugin.json';
const MARKETPLACE_RELATIVE = '.agents/plugins/marketplace.json';
const GENERATED_MARKER = '# Generated by scripts/generate-platform-artifacts.cjs. Do not edit.';
const GENERATED_SKILL_MARKER = '<!-- Generated by scripts/generate-platform-artifacts.cjs. Do not edit. -->';
const CODEX_RUNTIME_COPY_ENTRIES = Object.freeze([
  '.mcp.json',
  'spk.config.schema.json',
  'hooks',
  'mcp',
  'scripts',
  'templates',
]);

const FORBIDDEN_SHARED_SKILL_PATTERNS = [
  {
    label: 'Claude Task dispatch',
    pattern: /\bTask\s*\(/,
  },
  {
    label: 'Claude argument expansion',
    pattern: /\$ARGUMENTS\b/,
  },
  {
    label: 'Claude pre-computed shell expansion',
    pattern: /^!\s*`/m,
  },
  {
    label: 'Claude namespaced slash invocation',
    pattern: /\/spk:/,
  },
  {
    label: 'provider model identifier',
    pattern: /\b(?:claude-(?:opus|sonnet|haiku)|gpt-\d[\w.-]*)\b/i,
  },
];

const SHARED_SKILL_FRONTMATTER_KEYS = new Set([
  'allowed-tools',
  'description',
  'license',
  'metadata',
  'name',
]);

const CLAUDE_SKILL_FRONTMATTER_KEYS = new Set([
  ...SHARED_SKILL_FRONTMATTER_KEYS,
  'disable-model-invocation',
]);

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function loadInputs(repoRoot = REPO_ROOT) {
  return {
    contract: readJson(path.join(repoRoot, CONTRACT_RELATIVE)),
    manifest: readJson(path.join(repoRoot, MANIFEST_RELATIVE)),
  };
}

function requireNonEmptyString(value, label, errors) {
  if (typeof value !== 'string' || value.trim() === '') {
    errors.push(`${label} must be a non-empty string`);
    return false;
  }
  return true;
}

function requireStringArray(value, label, errors, minimum = 1) {
  if (!Array.isArray(value) || value.length < minimum) {
    errors.push(`${label} must contain at least ${minimum} item(s)`);
    return false;
  }
  value.forEach((item, index) => {
    requireNonEmptyString(item, `${label}[${index}]`, errors);
  });
  return true;
}

function normalizedCommandIds(manifest) {
  if (!manifest || !Array.isArray(manifest.commands)) {
    return [];
  }
  return manifest.commands.map((command) =>
    typeof command.name === 'string' ? command.name.replace(/^\//, '') : '',
  );
}

function validateContract(contract, manifest) {
  const errors = [];

  if (!contract || typeof contract !== 'object' || Array.isArray(contract)) {
    return ['contract must be a JSON object'];
  }
  if (contract.schemaVersion !== 2) {
    errors.push('schemaVersion must be 2');
  }

  const plugin = contract.plugin;
  if (!plugin || typeof plugin !== 'object' || Array.isArray(plugin)) {
    errors.push('plugin must be an object');
  } else {
    [
      'name',
      'displayName',
      'description',
      'longDescription',
      'developerName',
      'homepage',
      'repository',
      'license',
      'category',
    ].forEach((field) => requireNonEmptyString(plugin[field], `plugin.${field}`, errors));
    requireStringArray(plugin.keywords, 'plugin.keywords', errors);
    requireStringArray(plugin.capabilities, 'plugin.capabilities', errors);
    if (requireStringArray(plugin.defaultPrompts, 'plugin.defaultPrompts', errors)) {
      plugin.defaultPrompts.forEach((prompt, index) => {
        if (prompt.length > 128) {
          errors.push(`plugin.defaultPrompts[${index}] must be 128 characters or fewer`);
        }
      });
    }
    if (plugin.name !== manifest.slug) {
      errors.push(`plugin.name must match manifest.slug (${manifest.slug})`);
    }
  }

  const effectLevels = contract.effectLevels;
  if (!effectLevels || typeof effectLevels !== 'object' || Array.isArray(effectLevels)) {
    errors.push('effectLevels must be an object');
  }

  const approvalModes = contract.approvalModes;
  if (!approvalModes || typeof approvalModes !== 'object' || Array.isArray(approvalModes)) {
    errors.push('approvalModes must be an object');
  }

  const autonomyProfiles = contract.autonomyProfiles;
  if (!autonomyProfiles || typeof autonomyProfiles !== 'object' || Array.isArray(autonomyProfiles)) {
    errors.push('autonomyProfiles must be an object');
  } else {
    const expectedProfiles = ['afk_local', 'afk_to_pr', 'boundary_gated', 'decision_aware'];
    const actualProfiles = Object.keys(autonomyProfiles).sort();
    if (JSON.stringify(actualProfiles) !== JSON.stringify(expectedProfiles)) {
      errors.push(`autonomyProfiles must define exactly: ${expectedProfiles.join(', ')}`);
    }
    for (const [profileName, profile] of Object.entries(autonomyProfiles)) {
      const profileLabel = `autonomyProfiles.${profileName}`;
      if (!profile || typeof profile !== 'object' || Array.isArray(profile)) {
        errors.push(`${profileLabel} must be an object`);
        continue;
      }
      if (!Number.isInteger(profile.promptBudget) || profile.promptBudget < 0 || profile.promptBudget > 1) {
        errors.push(`${profileLabel}.promptBudget must be 0 or 1`);
      }
      if (!Number.isInteger(profile.repairBudget) || profile.repairBudget < 1 || profile.repairBudget > 3) {
        errors.push(`${profileLabel}.repairBudget must be between 1 and 3`);
      }
      requireNonEmptyString(profile.invocationAuthority, `${profileLabel}.invocationAuthority`, errors);
      requireNonEmptyString(profile.continuation, `${profileLabel}.continuation`, errors);
      requireStringArray(profile.pauseOnlyFor, `${profileLabel}.pauseOnlyFor`, errors);
      requireNonEmptyString(profile.checkpoint, `${profileLabel}.checkpoint`, errors);
    }
  }

  if (!Array.isArray(contract.skills)) {
    errors.push('skills must be an array');
    return errors;
  }

  const commandIds = normalizedCommandIds(manifest);
  const contractIds = contract.skills.map((skill) => skill && skill.id);
  const duplicateIds = contractIds.filter((id, index) => contractIds.indexOf(id) !== index);
  if (duplicateIds.length > 0) {
    errors.push(`skills contains duplicate ids: ${[...new Set(duplicateIds)].join(', ')}`);
  }
  const missingIds = commandIds.filter((id) => !contractIds.includes(id));
  const extraIds = contractIds.filter((id) => !commandIds.includes(id));
  if (missingIds.length > 0) {
    errors.push(`contract is missing manifest commands: ${missingIds.join(', ')}`);
  }
  if (extraIds.length > 0) {
    errors.push(`contract contains commands absent from manifest: ${extraIds.join(', ')}`);
  }

  const contractById = new Map(contract.skills
    .filter((skill) => skill && typeof skill.id === 'string')
    .map((skill) => [skill.id, skill]));
  const claimedSources = new Map();

  contract.skills.forEach((skill, skillIndex) => {
    const label = `skills[${skillIndex}]`;
    if (!skill || typeof skill !== 'object' || Array.isArray(skill)) {
      errors.push(`${label} must be an object`);
      return;
    }
    if (requireNonEmptyString(skill.id, `${label}.id`, errors)) {
      if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(skill.id)) {
        errors.push(`${label}.id must use lower-case kebab-case`);
      }
      if (`${manifest.slug}:${skill.id}`.length > 64) {
        errors.push(`${label}.id makes the plugin skill identity longer than 64 characters`);
      }
    }

    if (!['core', 'compat'].includes(skill.tier)) {
      errors.push(`${label}.tier must be core or compat`);
    }
    if (!skill.origin || typeof skill.origin !== 'object' || Array.isArray(skill.origin)) {
      errors.push(`${label}.origin must be an object`);
    } else {
      requireNonEmptyString(skill.origin.repository, `${label}.origin.repository`, errors);
      requireNonEmptyString(skill.origin.skill, `${label}.origin.skill`, errors);
    }

    const sourceBuckets = skill.tier === 'compat'
      ? 'compat'
      : '(?:engineering|productivity|operations|knowledge)';
    const sourcePatterns = {
      th: new RegExp(`^skills/${sourceBuckets}/${skill.id}$`),
      en: new RegExp(`^locales/en/skills/${sourceBuckets}/${skill.id}$`),
    };
    for (const locale of ['th', 'en']) {
      const source = skill.sources && skill.sources[locale];
      if (typeof source !== 'string' || !sourcePatterns[locale].test(source)) {
        errors.push(`${label}.sources.${locale} must be a canonical ${locale === 'th' ? 'Thai' : 'English'} skill directory`);
        continue;
      }
      if (claimedSources.has(source)) {
        errors.push(`${label}.sources.${locale} duplicates ${claimedSources.get(source)}`);
      } else {
        claimedSources.set(source, `${label}.sources.${locale}`);
      }
    }

    if (skill.tier === 'compat') {
      const target = contractById.get(skill.aliasFor);
      if (!target || target.tier !== 'core' || target.id === skill.id) {
        errors.push(`${label}.aliasFor must reference a canonical core skill`);
      }
    } else if (skill.aliasFor !== undefined) {
      errors.push(`${label}.aliasFor is allowed only for compatibility skills`);
    }

    for (const locale of ['en', 'th']) {
      const metadata = skill.locales && skill.locales[locale];
      if (!metadata || typeof metadata !== 'object' || Array.isArray(metadata)) {
        errors.push(`${label}.locales.${locale} must be an object`);
        continue;
      }
      [
        'displayName',
        'description',
        'shortDescription',
        'defaultPrompt',
      ].forEach((field) =>
        requireNonEmptyString(metadata[field], `${label}.locales.${locale}.${field}`, errors),
      );
      requireStringArray(metadata.triggers, `${label}.locales.${locale}.triggers`, errors, 2);
      requireStringArray(
        metadata.negativeTriggers,
        `${label}.locales.${locale}.negativeTriggers`,
        errors,
        2,
      );
      if (typeof metadata.description === 'string' && metadata.description.length > 1024) {
        errors.push(`${label}.locales.${locale}.description must be 1,024 characters or fewer`);
      }
      if (typeof metadata.defaultPrompt === 'string' && metadata.defaultPrompt.length > 128) {
        errors.push(`${label}.locales.${locale}.defaultPrompt must be 128 characters or fewer`);
      }
    }

    if (
      !skill.activation ||
      typeof skill.activation.allowImplicitInvocation !== 'boolean'
    ) {
      errors.push(`${label}.activation.allowImplicitInvocation must be a boolean`);
    }
    if (
      typeof skill.effectLevel !== 'string' ||
      !effectLevels ||
      !Object.prototype.hasOwnProperty.call(effectLevels, skill.effectLevel)
    ) {
      errors.push(`${label}.effectLevel must reference a declared effect level`);
    }
    if (
      typeof skill.autonomyProfile !== 'string' ||
      !autonomyProfiles ||
      !Object.prototype.hasOwnProperty.call(autonomyProfiles, skill.autonomyProfile)
    ) {
      errors.push(`${label}.autonomyProfile must reference a declared autonomy profile`);
    }
    if (
      skill.approvalMode !== undefined &&
      (!approvalModes || !Object.prototype.hasOwnProperty.call(approvalModes, skill.approvalMode))
    ) {
      errors.push(`${label}.approvalMode must reference a declared approval mode`);
    }
    requireNonEmptyString(skill.role, `${label}.role`, errors);

    if (!Array.isArray(skill.workflow) || skill.workflow.length < 2) {
      errors.push(`${label}.workflow must contain at least two phases`);
    } else {
      const phases = [];
      skill.workflow.forEach((step, stepIndex) => {
        if (!step || typeof step !== 'object' || Array.isArray(step)) {
          errors.push(`${label}.workflow[${stepIndex}] must be an object`);
          return;
        }
        requireNonEmptyString(step.phase, `${label}.workflow[${stepIndex}].phase`, errors);
        requireNonEmptyString(
          step.instruction,
          `${label}.workflow[${stepIndex}].instruction`,
          errors,
        );
        phases.push(step.phase);
      });
      const duplicates = phases.filter((phase, index) => phases.indexOf(phase) !== index);
      if (duplicates.length > 0) {
        errors.push(`${label}.workflow has duplicate phases: ${[...new Set(duplicates)].join(', ')}`);
      }
    }

    requireStringArray(skill.artifacts, `${label}.artifacts`, errors);
    requireStringArray(skill.evidence, `${label}.evidence`, errors);
    requireStringArray(skill.guardrails, `${label}.guardrails`, errors);
  });

  const serialized = JSON.stringify(contract);
  FORBIDDEN_SHARED_SKILL_PATTERNS.forEach(({ label, pattern }) => {
    if (pattern.test(serialized)) {
      errors.push(`contract contains ${label}`);
    }
  });

  return errors;
}

function parseYamlScalar(rawValue) {
  const value = rawValue.trim();
  if (value.startsWith('"')) {
    try {
      return JSON.parse(value);
    } catch {
      return value;
    }
  }
  if (value.startsWith("'") && value.endsWith("'")) {
    return value.slice(1, -1).replace(/''/g, "'");
  }
  if (value === 'true') {
    return true;
  }
  if (value === 'false') {
    return false;
  }
  return value;
}

function parseFrontmatter(markdown) {
  const normalized = markdown.replace(/\r\n/g, '\n');
  const match = normalized.match(/^---\n([\s\S]*?)\n---(?:\n|$)/);
  if (!match) {
    return null;
  }
  const fields = {};
  for (const line of match[1].split('\n')) {
    const fieldMatch = line.match(/^([A-Za-z0-9_-]+):\s*(.*)$/);
    if (fieldMatch) {
      fields[fieldMatch[1]] = parseYamlScalar(fieldMatch[2]);
    }
  }
  return {
    fields,
    body: normalized.slice(match[0].length),
  };
}

function validateSharedSkills(repoRoot, contract) {
  const errors = [];

  for (const skill of contract.skills) {
    const relativePath = path.join(PLUGIN_ROOT_RELATIVE, 'skills', skill.id, 'SKILL.md');
    const absolutePath = path.join(repoRoot, relativePath);
    if (!fs.existsSync(absolutePath)) {
      errors.push(`${relativePath} is missing`);
      continue;
    }

    const markdown = fs.readFileSync(absolutePath, 'utf8');
    const parsed = parseFrontmatter(markdown);
    if (!parsed) {
      errors.push(`${relativePath} must start with YAML frontmatter`);
      continue;
    }
    if (parsed.fields.name !== skill.id) {
      errors.push(`${relativePath} name must be ${skill.id}`);
    }
    if (parsed.fields.description !== skill.locales.en.description) {
      errors.push(`${relativePath} description must match the canonical contract`);
    }
    const unsupportedFrontmatter = Object.keys(parsed.fields)
      .filter((key) => !CLAUDE_SKILL_FRONTMATTER_KEYS.has(key))
      .sort();
    if (unsupportedFrontmatter.length > 0) {
      errors.push(
        `${relativePath} contains unsupported Claude source frontmatter: ` +
        unsupportedFrontmatter.join(', '),
      );
    }
    const disableModelInvocation =
      parsed.fields['disable-model-invocation'] ??
      parsed.fields.disable_model_invocation;
    const manualOnly = !skill.activation.allowImplicitInvocation;
    if (manualOnly && disableModelInvocation !== true) {
      errors.push(
        `${relativePath} must set disable-model-invocation: true for Claude manual-only parity`,
      );
    }
    if (!manualOnly && disableModelInvocation !== undefined) {
      errors.push(
        `${relativePath} must omit disable-model-invocation when implicit invocation is allowed`,
      );
    }
    if (parsed.body.trim() === '') {
      errors.push(`${relativePath} body must not be empty`);
    }

    for (const heading of ['## Workflow', '## Evidence Receipt', '## Guardrails']) {
      if (!parsed.body.includes(heading)) {
        errors.push(`${relativePath} must include ${heading}`);
      }
    }

    FORBIDDEN_SHARED_SKILL_PATTERNS.forEach(({ label, pattern }) => {
      if (pattern.test(markdown)) {
        errors.push(`${relativePath} contains ${label}`);
      }
    });
  }

  return errors;
}

function validatePackagingIsolation(repoRoot, contract) {
  const errors = [];
  const legacyManifest = path.join(
    repoRoot,
    PLUGIN_ROOT_RELATIVE,
    '.codex-plugin',
    'plugin.json',
  );
  if (fs.existsSync(legacyManifest)) {
    errors.push(
      'plugins/spk/.codex-plugin/plugin.json must not exist; Codex ships from plugins/spk-codex',
    );
  }
  for (const skill of contract.skills) {
    const legacyMetadata = path.join(
      repoRoot,
      PLUGIN_ROOT_RELATIVE,
      'skills',
      skill.id,
      'agents',
      'openai.yaml',
    );
    if (fs.existsSync(legacyMetadata)) {
      errors.push(
        `${path.relative(repoRoot, legacyMetadata)} must not exist in the Claude source payload`,
      );
    }
  }
  return errors;
}

function yamlString(value) {
  return JSON.stringify(value);
}

function renderCodexSkill(markdown) {
  const normalized = markdown.replace(/\r\n/g, '\n');
  const match = normalized.match(/^---\n([\s\S]*?)\n---(?:\n|$)/);
  if (!match) {
    throw new Error('cannot render Codex skill without YAML frontmatter');
  }
  const frontmatter = match[1]
    .split('\n')
    .filter((line) => !/^disable[-_]model[-_]invocation\s*:/.test(line))
    .join('\n');
  const body = normalized.slice(match[0].length).replace(/^\n+/, '');
  return [
    '---',
    frontmatter,
    '---',
    '',
    GENERATED_SKILL_MARKER,
    '',
    body.replace(/\n*$/, ''),
    '',
  ].join('\n');
}

function renderOpenAiYaml(skill, locale = 'en') {
  const metadata = skill.locales[locale];
  const commandPrefix = locale === 'th' ? 'ใช้' : 'Use';
  return [
    GENERATED_MARKER,
    'interface:',
    `  display_name: ${yamlString(metadata.displayName)}`,
    `  short_description: ${yamlString(metadata.shortDescription)}`,
    `  default_prompt: ${yamlString(`${commandPrefix} $spk:${skill.id}: ${metadata.defaultPrompt}`)}`,
    '',
    'policy:',
    `  allow_implicit_invocation: ${skill.activation.allowImplicitInvocation}`,
    '',
  ].join('\n');
}

